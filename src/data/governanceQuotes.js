/**
 * Get a random quote for the given governance type
 * @param {'monarchy' | 'republic'} type
 * @returns {string}
 */
export function getGovernanceQuote(type) {
    const pool = type === 'republic' ? REPUBLIC_QUOTES : MONARCHY_QUOTES;
    return pool[Math.floor(Math.random() * pool.length)];
}
